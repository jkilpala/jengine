local function index_of(path)
    for i, p in ipairs(M.TOUR) do
        if p == path then return i end
    end
    return nil
end

-- Leave in silence: music and the sounds a script started belong to the
-- audio backend, not the world, so they would play on into the next scene.
local function go(path)
    Audio.stop_all()
    Scene.load(path)
end

-- Call once per frame from update(). `current_scene_path` should be
-- the asset-relative path of the scene running this script.
function M.tick(current_scene_path)
    if Input.is_action_just_pressed("hub") or Input.is_action_just_pressed("cancel") then
        go(M.HUB)
        return
    end
    local i = index_of(current_scene_path)
    if not i then return end
    if Input.is_action_just_pressed("next_scene") and i < #M.TOUR then
        go(M.TOUR[i + 1])
    elseif Input.is_action_just_pressed("prev_scene") and i > 1 then
        go(M.TOUR[i - 1])
    end
end

return M
