//! Sprite atlas data — region rects, animation clips, and build-time
//! manifests. Backend-agnostic: the wgpu renderer keys textures by string
//! id and queries `AtlasData` for region UV rects.

use std::collections::HashMap;

use serde::{Deserialize, Serialize};

/// A named point within a sprite region (e.g. "barrel_tip", "hand_left").
/// Coordinates are in pixels relative to the region's top-left corner.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SpritePoint {
    pub name: String,
    /// X offset in pixels from the region's left edge.
    pub x: f32,
    /// Y offset in pixels from the region's top edge.
    pub y: f32,
}

/// A region within a sprite atlas texture.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AtlasRegion {
    pub name: String,
    pub x: u32,
    pub y: u32,
    pub width: u32,
    pub height: u32,
    /// Anchor/pivot point as a fraction of width/height (0.0–1.0).
    /// [0.5, 0.5] = center (default).
    #[serde(default = "default_anchor")]
    pub anchor: [f32; 2],
    /// Custom named points on this sprite (e.g. weapon attach points).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub points: Vec<SpritePoint>,
}

fn default_anchor() -> [f32; 2] {
    [0.5, 0.5]
}

impl AtlasRegion {
    /// Convert pixel coordinates to UV rect [u_min, v_min, u_max, v_max].
    pub fn uv_rect(&self, atlas_width: u32, atlas_height: u32) -> [f32; 4] {
        let u_min = self.x as f32 / atlas_width as f32;
        let v_min = self.y as f32 / atlas_height as f32;
        let u_max = (self.x + self.width) as f32 / atlas_width as f32;
        let v_max = (self.y + self.height) as f32 / atlas_height as f32;
        [u_min, v_min, u_max, v_max]
    }
}

/// The runtime id of an atlas referenced as `rel` (a `.atlas` path): its
/// sibling image, `sprites/x.atlas` -> `sprites/x.png`, with forward slashes.
///
/// That id is both the texture the image is loaded under and the key the
/// `AtlasData` is registered under, so a sprite whose `texture_id` names the
/// image can find its atlas - which is how animation frames resolve regions.
pub fn derive_atlas_id(rel: &str) -> String {
    let normalized = rel.replace('\\', "/");
    match normalized.rsplit_once('.') {
        Some((stem, _)) => format!("{stem}.png"),
        None => format!("{normalized}.png"),
    }
}

/// The `.atlas` paths a scene lists in its top-level `atlas_refs`.
pub fn scene_atlas_refs(scene_json: &serde_json::Value) -> Vec<String> {
    scene_json
        .get("atlas_refs")
        .and_then(|v| v.as_array())
        .map(|refs| {
            refs.iter()
                .filter_map(|r| r.as_str())
                .filter(|r| !r.is_empty())
                .map(str::to_string)
                .collect()
        })
        .unwrap_or_default()
}

/// Maps original sprite paths to their atlas location (written by the build
/// pipeline, read by the runtime).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AtlasManifest {
    pub entries: HashMap<String, AtlasManifestEntry>,
    pub atlases: Vec<AtlasFileEntry>,
}

/// A single entry in the atlas manifest.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AtlasManifestEntry {
    pub atlas_texture: String,
    pub region_name: String,
    /// Pre-computed UV rect [u_min, v_min, u_max, v_max].
    pub uv_rect: [f32; 4],
}

/// An atlas file generated by the pipeline.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AtlasFileEntry {
    pub image_path: String,
    pub meta_path: String,
    pub region_count: usize,
    pub width: u32,
    pub height: u32,
}

/// Atlas metadata — JSON file that accompanies the atlas image.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AtlasData {
    pub width: u32,
    pub height: u32,
    pub regions: Vec<AtlasRegion>,
    /// Animation clips defined in the atlas (resolved at build time).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub animation_clips: Vec<AtlasAnimationClip>,
}

impl AtlasData {
    /// Look up a region by name and return its UV rect.
    pub fn get_uv_rect(&self, name: &str) -> Option<[f32; 4]> {
        self.regions
            .iter()
            .find(|r| r.name == name)
            .map(|r| r.uv_rect(self.width, self.height))
    }

    /// Get a region by name.
    pub fn get_region(&self, name: &str) -> Option<&AtlasRegion> {
        self.regions.iter().find(|r| r.name == name)
    }
}

/// A fully resolved animation clip in a built atlas.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AtlasAnimationClip {
    pub name: String,
    pub fps: f32,
    pub looping: bool,
    pub frames: Vec<AtlasAnimFrame>,
}

/// A single frame within an atlas animation clip.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AtlasAnimFrame {
    pub region_name: String,
    /// Fully resolved named points for this frame.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub points: Vec<SpritePoint>,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_atlas_id_is_the_sibling_image() {
        assert_eq!(derive_atlas_id("sprites/creatures.atlas"), "sprites/creatures.png");
        assert_eq!(derive_atlas_id(r"sprites\_atlases\demo.atlas"), "sprites/_atlases/demo.png");
    }

    #[test]
    fn scene_atlas_refs_skips_junk() {
        let scene = serde_json::json!({ "atlas_refs": ["a.atlas", 3, "", "b.atlas"] });
        assert_eq!(scene_atlas_refs(&scene), vec!["a.atlas", "b.atlas"]);
        assert!(scene_atlas_refs(&serde_json::json!({})).is_empty());
    }

    #[test]
    fn registering_an_atlas_maps_its_regions() {
        let data: AtlasData = serde_json::from_value(serde_json::json!({
            "width": 64, "height": 32,
            "regions": [ { "name": "a", "x": 0, "y": 0, "width": 32, "height": 32 } ]
        }))
        .unwrap();
        let mut assets = crate::asset::AssetManager::new();
        assets.register_atlas("sheet.png".into(), data);
        assert!(assets.has_atlas_data("sheet.png"));
        assert_eq!(assets.atlas_lookup_entry("a"), Some(("sheet.png".into(), "a".into())));
    }
}
