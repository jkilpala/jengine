/**
 * sync-changelog.ts
 *
 * Turns the repository's root CHANGELOG.md (Keep a Changelog format:
 * `## [Unreleased]`, `## [0.1.0] - 2026-10-22`, `### Added` / `### Changed` /
 * `### Removed` / `### Fixed` ..., bullet lists, link references at the end)
 * into the site's Changelog page.
 *
 * The page carries no date of its own - the release headings have theirs -
 * so the same CHANGELOG.md always gives the same page, which is what lets CI
 * check that the committed page is current. Without a CHANGELOG.md the page
 * says so rather than failing the build.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync } from 'fs';
import { resolve, dirname } from 'path';
import { linkRepoPathsTo } from './repo-links';

const REPO_ROOT = process.env.JENGINE_ROOT || resolve(import.meta.dirname, '../..');
const INPUT = resolve(REPO_ROOT, 'CHANGELOG.md');
const OUTPUT = resolve(import.meta.dirname, '../src/content/docs/changelog/index.md');
// The page this one replaced: a roadmap built from archived phase plans,
// which listed long-shipped features as "Planned".
const RETIRED = resolve(import.meta.dirname, '../src/content/docs/changelog/roadmap.mdx');

const REPO_URL = 'https://github.com/jkilpala/jengine';

/** Raw HTML would be swallowed by the markdown renderer: `<project>` is not a tag. */
function escapeAngles(line: string): string {
  // Leave inline code spans alone; escape `<` everywhere else.
  return line
    .split(/(`+[^`]*`+)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/</g, '&lt;')))
    .join('');
}

export interface Release {
  version: string;
  date: string | null;
}

/** The release headings, newest first, as the file lists them. */
export function releases(md: string): Release[] {
  const out: Release[] = [];
  for (const line of md.split(/\r?\n/)) {
    const m = line.match(/^##\s+\[([^\]]+)\](?:\s*[-–—]\s*(\S+))?/);
    if (m) out.push({ version: m[1], date: m[2] ?? null });
  }
  return out;
}

/** CHANGELOG.md -> page body: the `# Changelog` title dropped, everything else kept. */
export function changelogBody(md: string): string {
  const out: string[] = [];
  let inFence = false;
  let droppedTitle = false;
  for (const raw of md.replace(/\r\n/g, '\n').split('\n')) {
    let line = raw;
    if (/^\s*```/.test(line)) {
      inFence = !inFence;
      out.push(line);
      continue;
    }
    if (inFence) { out.push(line); continue; }
    if (!droppedTitle && /^#\s+/.test(line)) { droppedTitle = true; continue; }
    // Link reference definitions (`[0.1.0]: https://...`) stay as they are.
    if (/^\[[^\]]+\]:\s*\S+/.test(line)) { out.push(line); continue; }
    // A relative link names a file in the repository: point it there.
    out.push(escapeAngles(linkRepoPathsTo(line, REPO_URL)));
  }
  return out.join('\n').trim();
}

export function renderChangelog(md: string | null): string {
  const L: string[] = [];
  L.push('---');
  L.push('title: Changelog');
  L.push('description: What changed in each jEngine release.');
  L.push('sidebar:');
  L.push('  badge:');
  L.push('    text: Auto-synced');
  L.push('    variant: tip');
  L.push('---');
  L.push('');
  L.push('<!-- Generated by website/scripts/sync-changelog.ts from CHANGELOG.md. Do not edit: change CHANGELOG.md and run `npm run sync`. -->');
  L.push('');
  L.push(`<p class="auto-generated">Generated from <code>CHANGELOG.md</code> in the repository root.</p>`);
  L.push('');
  L.push('jEngine is pre-1.0: any 0.x release may break the script API, the scene and project formats,');
  L.push('the package API and save formats, and every such break is listed here. See');
  L.push('[Versioning & Stability](/getting-started/versioning/).');
  L.push('');
  if (md === null) {
    L.push('No `CHANGELOG.md` was found in this checkout, so there is no release history to show.');
  } else {
    L.push(changelogBody(md));
  }
  L.push('');
  L.push('## What is next');
  L.push('');
  L.push('There is no fixed roadmap and no promised dates. Open ideas and known gaps are kept in the');
  L.push(`repository: [\`docs/feature-backlog.md\`](${REPO_URL}/blob/main/docs/feature-backlog.md) and`);
  L.push(`[\`docs/parity-gaps.md\`](${REPO_URL}/blob/main/docs/parity-gaps.md), where the four script runtimes still differ.`);
  L.push('');
  return L.join('\n');
}

export function syncChangelog(): void {
  console.log('[sync] Generating changelog');
  const md = existsSync(INPUT) ? readFileSync(INPUT, 'utf-8') : null;
  if (md === null) console.warn(`[sync]   no CHANGELOG.md at ${INPUT}; writing a placeholder page`);
  mkdirSync(dirname(OUTPUT), { recursive: true });
  const page = renderChangelog(md);
  if (!existsSync(OUTPUT) || readFileSync(OUTPUT, 'utf-8') !== page) writeFileSync(OUTPUT, page, 'utf-8');
  if (existsSync(RETIRED)) rmSync(RETIRED);
  const rel = md ? releases(md) : [];
  console.log('[sync] Written changelog →', OUTPUT);
  console.log(`[sync]   ${rel.length} release heading(s)${rel.length ? `, newest ${rel[0].version}` : ''}`);
}

if (import.meta.url === `file:///${process.argv[1]?.replace(/\\/g, '/')}` ||
    process.argv[1]?.endsWith('sync-changelog.ts')) {
  syncChangelog();
}
