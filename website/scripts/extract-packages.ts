/**
 * extract-packages.ts
 *
 * One page per engine package under `packages/`, plus an index, written to
 * src/content/docs/packages/. Each page is two halves:
 *
 *   - facts read from the source, so they cannot drift: the components the
 *     package registers, its script commands under the namespace scripts call
 *     them by, the packages it depends on, the projects that list it and the
 *     scenes that use its components;
 *   - the package's own prose: its README.md, or the `//!` crate doc in
 *     src/lib.rs when it has no README.
 *
 * So to change a package's page, change its README or crate doc and run
 * `npm run sync` (or `npm run sync:packages`). Never edit the output.
 *
 * `--check` writes nothing: it fails if a package has no documentation or a
 * generated page is out of date. The Claude Code hooks in .claude/hooks/ use
 * both modes.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, statSync, rmSync } from 'fs';
import { resolve, join, relative } from 'path';
import { unlinkRepoPaths } from './repo-links';

const REPO_ROOT = process.env.JENGINE_ROOT || resolve(import.meta.dirname, '../..');
const PACKAGES_DIR = resolve(REPO_ROOT, 'packages');
const PROJECTS_DIR = resolve(REPO_ROOT, 'projects');
const RUNTIME_CARGO = resolve(REPO_ROOT, 'crates/jengine-runtime/Cargo.toml');
const OUTPUT_DIR = resolve(import.meta.dirname, '../src/content/docs/packages');

/** A crate doc shorter than this is a stub, not documentation. */
const MIN_DOC_LINES = 3;

const GENERATED_NOTE =
  '<!-- Generated by website/scripts/extract-packages.ts from the package source. Do not edit: ' +
  "change the package's README.md or `//!` crate doc and run `npm run sync`. -->";

// Core's namespaces (scripting/namespaces.rs `core_namespaces`): a package
// namespace equal to one of these is refused, so its commands stay flat.
// Read from the source so the list cannot go stale.
function coreNamespaces(): Set<string> {
  const src = readFileSync(resolve(REPO_ROOT, 'crates/jengine-core/src/scripting/namespaces.rs'), 'utf-8');
  const out = new Set<string>();
  // CORE rows: ("Entity", "spawn", "spawn_entity")
  for (const m of src.matchAll(/\(\s*"([A-Z][A-Za-z0-9]*)"\s*,\s*"[a-z_0-9]+"\s*,\s*"[a-z_0-9]+"\s*\)/g)) out.add(m[1]);
  return out;
}

/** Component keys core registers itself; those work in v1 scenes too. */
function coreComponentKeys(): Set<string> {
  const src = readFileSync(resolve(REPO_ROOT, 'crates/jengine-core/src/package/core_registration.rs'), 'utf-8');
  return new Set(extractComponents(src).map(c => c.key));
}

export interface PackageCommand {
  flat: string;
  args: string[];
  /** `Online.join`, or the flat name when the namespace is refused. */
  call: string;
}

export interface PackageInfo {
  name: string;
  slug: string;
  description: string;
  version: string;
  builtIn: boolean;
  entryPoint: string;
  namespace: string | null;
  components: Array<{ key: string; type: string; core: boolean }>;
  commands: PackageCommand[];
  dependsOn: string[];
  usedBy: string[];
  scenes: string[];
  docSource: 'README.md' | 'src/lib.rs' | null;
  body: string;
}

// ── source reading ──────────────────────────────────────────────────────────

function rustFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const entry of readdirSync(dir).sort()) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) out.push(...rustFiles(p));
    else if (p.endsWith('.rs')) out.push(p);
  }
  return out;
}

function tomlString(src: string, key: string): string | null {
  const m = src.match(new RegExp(`^${key}\\s*=\\s*"([^"]*)"`, 'm'));
  return m ? m[1] : null;
}

/** `jengine-online` -> `Online`, as `package_namespace` does it. */
export function packageNamespace(pkg: string): string {
  const base = pkg.startsWith('jengine-') ? pkg.slice('jengine-'.length) : pkg;
  return base
    .split(/[-_]/)
    .filter(Boolean)
    .map(p => p[0].toUpperCase() + p.slice(1))
    .join('');
}

const LUA_KEYWORDS = new Set([
  'and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'goto', 'if', 'in',
  'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while',
]);

/** The rule of `package_entries`: drop a prefix every command shares. */
function shortNames(flat: string[]): Map<string, string> {
  const out = new Map<string, string>();
  const first = flat[0] ?? '';
  const head = first.includes('_') ? first.slice(0, first.indexOf('_') + 1) : null;
  const shared = head !== null && flat.every(n => n.length > head.length && n.startsWith(head));
  for (const n of flat) {
    const rest = shared ? n.slice(head!.length) : n;
    const usable = /^[A-Za-z_]/.test(rest) && !LUA_KEYWORDS.has(rest);
    out.set(n, usable ? rest : n);
  }
  return out;
}

function stripComments(src: string): string {
  return src.replace(/^\s*\/\/.*$/gm, '');
}

function extractComponents(src: string): Array<{ key: string; type: string }> {
  const out: Array<{ key: string; type: string }> = [];
  const re = /\.register(?:_defaulted)?::<\s*([\w:]+)\s*>\(\s*"([^"]+)"/g;
  for (const m of src.matchAll(re)) out.push({ type: m[1].split('::').pop()!, key: m[2] });
  return out;
}

function extractCommands(src: string): Array<{ flat: string; args: string[]; pkgArg: string }> {
  const out: Array<{ flat: string; args: string[]; pkgArg: string }> = [];
  const parseArgs = (s: string) => [...s.matchAll(/"([^"]*)"/g)].map(m => m[1]);
  // c.register(PACKAGE, "plat_input", &["e", "x"], |host, args| ...
  const re = /\.register\(\s*([A-Z_]+|"[^"]+")\s*,\s*"([a-z][a-z0-9_]*)"\s*,\s*&\[([^\]]*)\]/g;
  for (const m of src.matchAll(re)) out.push({ pkgArg: m[1], flat: m[2], args: parseArgs(m[3]) });
  // A helper macro whose body registers `$name`: simple!("gb_enter", ...)
  const macroRe = /macro_rules!\s*(\w+)\s*\{([\s\S]*?)\n\s*\}\s*\n/g;
  for (const mac of src.matchAll(macroRe)) {
    const body = mac[2].match(/\.register\(\s*([A-Z_]+|"[^"]+")\s*,\s*\$\w+\s*,\s*&\[([^\]]*)\]/);
    if (!body) continue;
    for (const call of src.matchAll(new RegExp(`\\b${mac[1]}!\\(\\s*"([a-z][a-z0-9_]*)"`, 'g'))) {
      out.push({ pkgArg: body[1], flat: call[1], args: parseArgs(body[2]) });
    }
  }
  return out;
}

/** Scaffold text nobody has replaced yet (`jengine package new` writes TODOs
 * and `{{UPPER_CASE}}` tokens). Only a token counts: a README may well show a
 * nested Lua table, `{{x, y, r}, ...}`, as a crowd package's might. */
function isUnfinished(doc: string): boolean {
  return /\bTODO\b/.test(doc) || /\{\{[A-Z][A-Z0-9_]*\}\}/.test(doc);
}

/** The `//!` block at the top of lib.rs, as markdown. */
function crateDoc(libRs: string): string {
  const lines: string[] = [];
  for (const line of libRs.split(/\r?\n/)) {
    const t = line.trimStart();
    if (t.startsWith('//!')) lines.push(t.replace(/^\/\/!\s?/, ''));
    else if (t === '' && lines.length === 0) continue;
    else if (t.startsWith('#![')) continue;
    else break;
  }
  return lines.join('\n').trim();
}

/**
 * Rustdoc and README prose -> markdown that sits under the page's own
 * headings: headings demoted one level below `##`, rustdoc intra-doc links
 * turned into code, and rustdoc code fences given a language Starlight knows.
 */
function toPageMarkdown(md: string, fromRustdoc: boolean): string {
  const out: string[] = [];
  let inFence = false;
  let droppedTitle = false;
  for (let line of md.split(/\r?\n/)) {
    const fence = line.match(/^(\s*)```(.*)$/);
    if (fence) {
      if (!inFence) {
        let lang = fence[2].trim().split(',')[0];
        if (fromRustdoc && (lang === '' || ['ignore', 'no_run', 'should_panic', 'compile_fail'].includes(lang))) lang = 'rust';
        if (lang === 'text' || lang === 'txt') lang = 'text';
        line = `${fence[1]}\`\`\`${lang}`;
      }
      inFence = !inFence;
      out.push(line);
      continue;
    }
    if (inFence) { out.push(line); continue; }
    const heading = line.match(/^(#{1,5})\s+(.*)$/);
    if (heading) {
      // A README's own `# jengine-x` title duplicates the page title.
      if (!fromRustdoc && heading[1] === '#' && !droppedTitle) { droppedTitle = true; continue; }
      const depth = Math.min(fromRustdoc ? heading[1].length + 2 : Math.max(heading[1].length + 1, 3), 6);
      out.push(`${'#'.repeat(depth)} ${heading[2]}`);
      continue;
    }
    if (fromRustdoc) {
      // [`Foo`] / [`Foo`](path) / [Foo] -> `Foo`
      line = line
        .replace(/\[(`[^`\]]+`)\]\((?:[^)\s]+)\)/g, '$1')
        .replace(/\[(`[^`\]]+`)\](?![\[(:])/g, '$1');
    }
    out.push(unlinkRepoPaths(line));
  }
  return out.join('\n').trim();
}

function projectsListing(): Map<string, string[]> {
  const out = new Map<string, string[]>();
  if (!existsSync(PROJECTS_DIR)) return out;
  for (const project of readdirSync(PROJECTS_DIR).sort()) {
    const manifest = join(PROJECTS_DIR, project, 'project.jengine');
    if (!existsSync(manifest)) continue;
    try {
      const json = JSON.parse(readFileSync(manifest, 'utf-8'));
      for (const p of json.packages ?? []) {
        if (!p?.name) continue;
        out.set(p.name, [...(out.get(p.name) ?? []), project]);
      }
    } catch { /* a broken manifest is someone else's test */ }
  }
  return out;
}

function sceneFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const entry of readdirSync(dir).sort()) {
    if (entry === 'node_modules' || entry === '.jengine' || entry === 'target') continue;
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) out.push(...sceneFiles(p));
    else if (p.endsWith('.scene')) out.push(p);
  }
  return out;
}

/** Scene path -> the component keys it authors. */
function sceneKeys(): Map<string, Set<string>> {
  const out = new Map<string, Set<string>>();
  for (const file of sceneFiles(PROJECTS_DIR)) {
    const text = readFileSync(file, 'utf-8');
    const keys = new Set<string>();
    for (const m of text.matchAll(/"([a-z][a-z0-9_]*)"\s*:/g)) keys.add(m[1]);
    out.set(relative(REPO_ROOT, file).replace(/\\/g, '/'), keys);
  }
  return out;
}

export function readPackages(): PackageInfo[] {
  const builtInSrc = existsSync(RUNTIME_CARGO) ? readFileSync(RUNTIME_CARGO, 'utf-8') : '';
  const builtIns = new Set([...builtInSrc.matchAll(/^(jengine-[a-z0-9-]+)\s*=\s*\{\s*path\s*=\s*"[^"]*packages\//gm)].map(m => m[1]));
  const listedBy = projectsListing();
  const scenes = sceneKeys();
  const taken = coreNamespaces();
  const coreKeys = coreComponentKeys();
  // A tree with no packages/ - or only some of them, as the public export
  // keeps just the engine's own - still generates: every list is read from
  // what is there, and links only go to pages this run writes.
  const all = new Set(existsSync(PACKAGES_DIR)
    ? readdirSync(PACKAGES_DIR).filter(d => existsSync(join(PACKAGES_DIR, d, 'Cargo.toml')))
    : []);

  const out: PackageInfo[] = [];
  for (const dir of [...all].sort()) {
    const root = join(PACKAGES_DIR, dir);
    const cargo = readFileSync(join(root, 'Cargo.toml'), 'utf-8');
    const pkgToml = existsSync(join(root, 'package.toml')) ? readFileSync(join(root, 'package.toml'), 'utf-8') : '';
    const name = tomlString(cargo, 'name') ?? dir;
    const description = tomlString(pkgToml, 'description') ?? tomlString(cargo, 'description') ?? '';
    const version = tomlString(pkgToml, 'version') ?? tomlString(cargo, 'version') ?? '0.1.0';
    const crate = name.replace(/-/g, '_');
    const guessed = `${crate}::${packageNamespace(name)}Package`;
    const entryPoint = tomlString(pkgToml, 'entry_point') ?? guessed;

    const sources = rustFiles(join(root, 'src')).map(f => stripComments(readFileSync(f, 'utf-8')));
    const joined = sources.join('\n');
    const components = extractComponents(joined).map(c => ({ ...c, core: coreKeys.has(c.key) }));
    const rawCommands = extractCommands(joined);

    const pkgConst = joined.match(/const\s+PACKAGE\s*:\s*&str\s*=\s*"([^"]+)"/)?.[1] ?? name;
    const cmdPackage = rawCommands[0]
      ? (rawCommands[0].pkgArg.startsWith('"') ? rawCommands[0].pkgArg.slice(1, -1) : pkgConst)
      : name;
    let namespace: string | null = null;
    const shorts = shortNames(rawCommands.map(c => c.flat));
    if (rawCommands.length > 0) {
      const ns = packageNamespace(cmdPackage);
      // Namespaces are handed out in registration order; core's are taken
      // first. Package-vs-package collisions are a load-time error, so a
      // shipped set has none to model here.
      namespace = taken.has(ns) ? null : ns;
    }
    const seen = new Set<string>();
    const commands: PackageCommand[] = [];
    for (const c of rawCommands) {
      if (seen.has(c.flat)) continue;
      seen.add(c.flat);
      commands.push({ ...c, call: namespace ? `${namespace}.${shorts.get(c.flat)}` : c.flat });
    }

    const dependsOn = [...cargo.matchAll(/^(jengine-[a-z0-9-]+)\s*=\s*\{[^}]*path\s*=\s*"\.\.\/jengine-/gm)]
      .map(m => m[1])
      .filter(d => all.has(d) && d !== name);

    const keys = new Set(components.map(c => c.key));
    const usedScenes = [...scenes.entries()]
      .filter(([, k]) => [...keys].some(key => k.has(key)))
      .map(([p]) => p)
      .sort();

    // The README wins; without one, the crate doc. Either still carrying the
    // scaffold's TODOs is not documentation yet.
    let docSource: PackageInfo['docSource'] = null;
    let body = '';
    const readme = join(root, 'README.md');
    if (existsSync(readme) && readFileSync(readme, 'utf-8').trim().length > 0) {
      const text = readFileSync(readme, 'utf-8');
      if (!isUnfinished(text)) {
        docSource = 'README.md';
        body = toPageMarkdown(text, false);
      }
    } else {
      const lib = join(root, 'src/lib.rs');
      const doc = existsSync(lib) ? crateDoc(readFileSync(lib, 'utf-8')) : '';
      if (doc.split('\n').filter(l => l.trim()).length >= MIN_DOC_LINES && !isUnfinished(doc)) {
        docSource = 'src/lib.rs';
        body = toPageMarkdown(doc, true);
      }
    }
    if (/^TODO/i.test(description)) docSource = null;

    out.push({
      name,
      slug: name.replace(/^jengine-/, ''),
      description,
      version,
      builtIn: builtIns.has(name),
      entryPoint,
      namespace,
      components,
      commands,
      dependsOn,
      usedBy: listedBy.get(name) ?? [],
      scenes: usedScenes,
      docSource,
      body,
    });
  }
  return out;
}

// ── rendering ───────────────────────────────────────────────────────────────

function yamlString(s: string): string {
  return JSON.stringify(s);
}

function cell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function renderPage(p: PackageInfo, all: PackageInfo[]): string {
  const L: string[] = [];
  L.push('---');
  L.push(`title: ${yamlString(p.name)}`);
  L.push(`description: ${yamlString(p.description || `The ${p.name} package.`)}`);
  L.push('---');
  L.push('');
  L.push(GENERATED_NOTE);
  L.push('');
  if (p.description) { L.push(p.description.endsWith('.') ? p.description : `${p.description}.`); L.push(''); }

  L.push('| | |');
  L.push('|---|---|');
  L.push(`| Kind | ${p.builtIn ? 'Built-in: linked into the stock runtime and editor viewport' : 'Project package: linked into the builds of the projects that list it'} |`);
  L.push(`| Source | \`packages/${p.name}\` |`);
  L.push(`| Version | ${p.version} |`);
  L.push(`| Entry point | \`${p.entryPoint}\` |`);
  if (p.namespace) L.push(`| Script namespace | \`${p.namespace}\` |`);
  if (p.dependsOn.length) L.push(`| Depends on | ${p.dependsOn.map(d => `[${d}](/packages/${d.replace(/^jengine-/, '')}/)`).join(', ')} |`);
  if (p.usedBy.length) L.push(`| Listed by | ${p.usedBy.map(x => `\`projects/${x}\``).join(', ')} |`);
  L.push('');

  L.push('## Using it');
  L.push('');
  if (p.builtIn) {
    L.push('The stock runtime, web build and editor viewport are compiled with this package, so there is');
    L.push('nothing to link. A project that has a `settings.enabled_packages` list must name it there, since');
    L.push('that list is an allow-list once it exists; a project without the key gets every built-in.');
    L.push('');
    L.push('```json');
    L.push(`{ "settings": { "enabled_packages": ["${p.name}"] } }`);
    L.push('```');
  } else {
    const deps = closure(p, all);
    L.push(`List it in the top-level \`"packages"\` array of \`project.jengine\`${deps.length > 1 ? ', **together with every package it depends on**: a crate dependency compiles a package in but does not register it, and `packages_a_project_lists_cover_their_dependencies` fails a project that lists only the outer one' : ''}:`);
    L.push('');
    L.push('```json');
    L.push('{');
    L.push('  "packages": [');
    deps.forEach((d, i) => {
      L.push(`    { "name": "${d}", "source": { "type": "path", "path": "../../packages/${d}" } }${i < deps.length - 1 ? ',' : ''}`);
    });
    L.push('  ]');
    L.push('}');
    L.push('```');
    L.push('');
    L.push('Then rebuild the editor viewport for the project (`jengine viewport-build projects/<name>`, or the');
    L.push("editor's *Rebuild viewport* banner). Native and web builds link it on their own.");
  }
  if (p.components.some(c => !c.core)) {
    L.push('');
    L.push('A scene that uses its components must be a **v2** scene (`"version": 2`): a v1 scene has no field');
    L.push('for a package component and keeps it as inert custom data.');
  } else if (p.components.length) {
    L.push('');
    L.push('Its components are also core components, so v1 and v2 scenes both carry them.');
  }
  if (p.namespace) {
    L.push('');
    L.push(`A script can check that the package is linked with \`if ${p.namespace} == nil then return end\`.`);
  }
  L.push('');

  if (p.components.length) {
    L.push('## Components');
    L.push('');
    L.push('| Scene key | Rust type | |');
    L.push('|---|---|---|');
    for (const c of p.components) L.push(`| \`${c.key}\` | \`${c.type}\` | ${c.core ? 'also registered by core' : 'package only: needs a v2 scene'} |`);
    L.push('');
  }

  if (p.commands.length) {
    L.push('## Script commands');
    L.push('');
    L.push('Commands run in every runtime and return nothing; a package publishes what scripts read onto');
    L.push('components (see the notes below). The flat name also works.');
    L.push('');
    L.push('| Call | Flat name |');
    L.push('|---|---|');
    for (const c of p.commands) L.push(`| \`${cell(c.call)}(${c.args.join(', ')})\` | \`${c.flat}\` |`);
    L.push('');
  }

  if (p.scenes.length) {
    L.push('## Scenes that use it');
    L.push('');
    const shown = p.scenes.slice(0, 12);
    for (const s of shown) L.push(`- \`${s}\``);
    if (p.scenes.length > shown.length) L.push(`- …and ${p.scenes.length - shown.length} more`);
    L.push('');
  }

  L.push('## Notes');
  L.push('');
  L.push(`*From \`packages/${p.name}/${p.docSource}\`.*`);
  L.push('');
  L.push(p.body);
  L.push('');
  return L.join('\n');
}

/** The package and everything it depends on, outermost first. */
function closure(p: PackageInfo, all: PackageInfo[]): string[] {
  const byName = new Map(all.map(x => [x.name, x]));
  const out: string[] = [];
  const visit = (n: string) => {
    if (out.includes(n)) return;
    out.push(n);
    for (const d of byName.get(n)?.dependsOn ?? []) visit(d);
  };
  visit(p.name);
  return out;
}

function renderIndex(all: PackageInfo[]): string {
  const L: string[] = [];
  L.push('---');
  L.push('title: Packages');
  L.push('description: Every engine package in the repository - what it is, what it registers and how to use it.');
  L.push('sidebar:');
  L.push('  order: 0');
  L.push('  label: All packages');
  L.push('---');
  L.push('');
  L.push(GENERATED_NOTE);
  L.push('');
  L.push(`The repository ships **${all.length} package${all.length === 1 ? '' : 's'}** under \`packages/\`. A package is a Rust crate that`);
  L.push('adds components, systems and script commands to the engine; see');
  L.push('[Custom Rust Components & Packages](/guides/packages/) for how they work and how to write one.');
  L.push('');
  L.push('Each page below is generated from the package itself: its registrations are read from the source,');
  L.push('and its prose is the package\'s README or crate doc.');
  L.push('');
  const table = (rows: PackageInfo[]) => {
    L.push('| Package | What it is | Script namespace | Components |');
    L.push('|---|---|---|---|');
    for (const p of rows) {
      L.push(`| [${p.name}](/packages/${p.slug}/) | ${cell(p.description)} | ${p.namespace ? `\`${p.namespace}\`` : '-'} | ${p.components.length} |`);
    }
    L.push('');
  };
  const builtIn = all.filter(p => p.builtIn);
  const rest = all.filter(p => !p.builtIn);
  if (builtIn.length) {
    L.push('## Built-in packages');
    L.push('');
    L.push('Linked into the stock native runtime, web build and editor viewport. A project switches them with');
    L.push('`settings.enabled_packages`.');
    L.push('');
    table(builtIn);
  }
  if (rest.length) {
    L.push('## Project packages');
    L.push('');
    L.push('Linked only into the builds of a project that lists them in `project.jengine`\'s `"packages"` array.');
    L.push('');
    table(rest);
  }
  return L.join('\n');
}

// ── entry points ────────────────────────────────────────────────────────────

/** Path -> content for every page this generator owns. */
export function renderPackagePages(): { pages: Map<string, string>; undocumented: string[] } {
  const all = readPackages();
  const pages = new Map<string, string>();
  pages.set(join(OUTPUT_DIR, 'index.md'), renderIndex(all));
  for (const p of all) {
    if (!p.docSource) continue;
    pages.set(join(OUTPUT_DIR, `${p.slug}.md`), renderPage(p, all));
  }
  return { pages, undocumented: all.filter(p => !p.docSource).map(p => p.name) };
}

function undocumentedMessage(names: string[]): string {
  return (
    `package(s) without documentation: ${names.join(', ')}. ` +
    `Give each a README.md (or, with no README, a \`//!\` crate doc of at least ${MIN_DOC_LINES} lines in src/lib.rs) ` +
    'saying what it is, its components, its script commands and what scripts read back, with no TODO left, ' +
    'and a description in package.toml or Cargo.toml - the website page is generated from them.'
  );
}

export function extractPackages(): void {
  const { pages, undocumented } = renderPackagePages();
  if (undocumented.length) {
    console.error(`[sync] ❌ ${undocumentedMessage(undocumented)}`);
    process.exit(1);
  }
  mkdirSync(OUTPUT_DIR, { recursive: true });
  // Drop pages of packages that no longer exist.
  for (const f of readdirSync(OUTPUT_DIR)) {
    const p = join(OUTPUT_DIR, f);
    if (f.endsWith('.md') && !pages.has(p)) rmSync(p);
  }
  let written = 0;
  for (const [path, content] of pages) {
    if (existsSync(path) && readFileSync(path, 'utf-8') === content) continue;
    writeFileSync(path, content, 'utf-8');
    written++;
  }
  console.log(`[sync] Package pages: ${pages.size - 1} packages, ${written} file(s) updated → ${OUTPUT_DIR}`);
}

/** Exit 1 with a reason if anything is undocumented or out of date. */
export function checkPackages(): void {
  const { pages, undocumented } = renderPackagePages();
  const problems: string[] = [];
  if (undocumented.length) problems.push(undocumentedMessage(undocumented));
  const stale: string[] = [];
  for (const [path, content] of pages) {
    if (!existsSync(path) || readFileSync(path, 'utf-8') !== content) stale.push(relative(REPO_ROOT, path).replace(/\\/g, '/'));
  }
  if (existsSync(OUTPUT_DIR)) {
    for (const f of readdirSync(OUTPUT_DIR)) {
      const p = join(OUTPUT_DIR, f);
      if (f.endsWith('.md') && !pages.has(p)) stale.push(`${relative(REPO_ROOT, p).replace(/\\/g, '/')} (package gone)`);
    }
  }
  if (stale.length) problems.push(`out-of-date website package page(s): ${stale.join(', ')} - run \`npm run sync:packages\` in website/`);
  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  console.log(`[check] ${pages.size - 1} package pages documented and up to date`);
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('extract-packages.ts')) {
  if (process.argv.includes('--check')) checkPackages();
  else extractPackages();
}
